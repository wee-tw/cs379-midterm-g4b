"""Timed measurement windows for whole-board power on PYNQ-Z2 (run ON THE BOARD).

PYNQ-Z2 has no on-board power sensing, so power comes from an external meter on the 5 V
input (USB meter, bench supply, or a Joulescope on J9 as in the MLPerf Tiny setup).
This script produces well-defined windows (>= 10 s each, repeated, MLPerf-style) and
logs their start/end times, so the meter's log can be cut into idle / continuous /
fixed-rate segments afterwards. It uses the PYNQ driver that FINN generates
(driver.py + driver_base.py in the deployment package).

  sudo python3 measure_power.py --deploy /home/xilinx/finn_rn8 \
      --clocks 50 66.67 100 125 --rates 30 300 1000 --seconds 12 --repeats 5
  sudo python3 measure_power.py --deploy /home/xilinx/finn_rn8 --halt-test
  # platform check before any ResNet-8 build, with the prebuilt finn-examples overlay:
  sudo python3 measure_power.py --example cnv_w1a1_cifar10 --halt-test

States per clock: overlay loaded but idle; idle with FCLK0 stopped; continuous
back-to-back batches; fixed rate R with the clock running between frames; fixed rate R
with race-to-halt (FCLK0 stopped between frames, baseline B5). Fixed-rate states run only
for R below the measured throughput.
Output: windows.csv with state, set/actual clock, rate, start/end (unix s), images done,
die temperature (XADC, if the Linux IIO driver exposes it).
"""

import argparse
import csv
import glob
import os
import sys
import time

SLCR_BASE = 0xF8000000
SLCR_UNLOCK, UNLOCK_KEY = 0x008, 0xDF0D
FPGA0_THR_CTRL, FPGA0_THR_CNT, FPGA0_THR_STA = 0x174, 0x178, 0x17C  # UG585 "Clock Throttle"
CPU_START, CNT_RST = 1 << 0, 1 << 1
STA_RUNNING = 1 << 16


class Fclk0Throttle:
    """Stop/restart FCLK0 through the PS clock throttle (UG585, PL Clocks > Clock Throttle).

    LAST_CNT = 0 means a free-running clock (the reset default). A non-zero LAST_CNT plus
    CPU_START runs that many pulses and then halts. The exact sequence is NOT yet verified
    on our board: run --halt-test first and check that the status bit and the outputs
    behave before measuring anything.
    """

    def __init__(self):
        from pynq import MMIO
        self.mmio = MMIO(SLCR_BASE, 0x200)
        self.mmio.write(SLCR_UNLOCK, UNLOCK_KEY)  # Linux normally leaves SLCR unlocked

    def running(self):
        return bool(self.mmio.read(FPGA0_THR_STA) & STA_RUNNING)

    def stop(self):
        self.mmio.write(FPGA0_THR_CNT, 1)
        self.mmio.write(FPGA0_THR_CTRL, CPU_START)

    def run(self):
        self.mmio.write(FPGA0_THR_CNT, 0)
        self.mmio.write(FPGA0_THR_CTRL, CNT_RST)
        self.mmio.write(FPGA0_THR_CTRL, CPU_START)


def die_temp_c():
    for d in glob.glob("/sys/bus/iio/devices/iio:device*"):
        try:
            raw = float(open(os.path.join(d, "in_temp0_raw")).read())
            off = float(open(os.path.join(d, "in_temp0_offset")).read())
            scale = float(open(os.path.join(d, "in_temp0_scale")).read())
            return f"{(raw + off) * scale / 1000:.1f}"
        except OSError:
            continue
    return ""


def load_accel(args, batch, fclk):
    """FINN deployment folder (our builds) or a prebuilt finn-examples overlay."""
    if args.example:
        from finn_examples import models   # pip3 install finn-examples (PYNQ image)
        accel = getattr(models, args.example)()
        accel.batch_size = batch
        return accel
    sys.path.insert(0, args.deploy)
    from driver import io_shape_dict          # generated by FINN's MakePYNQDriver
    from driver_base import FINNExampleOverlay
    return FINNExampleOverlay(bitfile_name=os.path.join(args.deploy, args.bitfile),
                              platform="zynq-iodma", io_shape_dict=io_shape_dict,
                              batch_size=batch, fclk_mhz=fclk)


def window(writer, state, f_set, f_act, rate, seconds, work):
    t0 = time.time()
    n = work(t0 + seconds)
    t1 = time.time()
    writer.writerow([state, f_set, f_act, rate, f"{t0:.3f}", f"{t1:.3f}", n,
                     f"{n / (t1 - t0):.1f}" if n else "", die_temp_c()])
    return n / (t1 - t0) if n else 0.0


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--deploy", help="FINN deployment folder (driver.py, bitfile/)")
    p.add_argument("--example", help="finn-examples model instead, e.g. cnv_w1a1_cifar10")
    p.add_argument("--bitfile", default="bitfile/finn-accel.bit")
    p.add_argument("--batch", type=int, default=1000)
    p.add_argument("--clocks", type=float, nargs="+", default=[50, 66.67, 100, 125])
    p.add_argument("--rates", type=float, nargs="+", default=[30, 300, 1000])
    p.add_argument("--seconds", type=float, default=12.0)
    p.add_argument("--repeats", type=int, default=5)
    p.add_argument("--no-halt", action="store_true", help="skip the clock-stop states")
    p.add_argument("--halt-test", action="store_true",
                   help="only check that FCLK0 can be stopped and restarted, then exit")
    p.add_argument("--out", default="windows.csv")
    args = p.parse_args()
    if not (args.deploy or args.example):
        p.error("give --deploy or --example")
    from pynq.ps import Clocks

    if args.halt_test:
        accel = load_accel(args, 1, args.clocks[-1])
        import numpy as np
        thr = Fclk0Throttle()
        ref = np.zeros_like(accel.obuf_packed_device[0])
        out = np.zeros_like(ref)
        accel.execute_on_buffers(batch_size=1)
        accel.copy_output_data_from_device(ref)
        print("running before stop:", thr.running())
        thr.stop()
        time.sleep(0.1)
        print("running after stop:", thr.running(), "(expect False)")
        thr.run()
        time.sleep(0.1)
        print("running after restart:", thr.running(), "(expect True)")
        accel.obuf_packed_device[0][:] = 0
        accel.obuf_packed_device[0].flush()
        accel.execute_on_buffers(batch_size=1)
        accel.copy_output_data_from_device(out)
        print("output unchanged after stop/restart:", bool((out == ref).all()))
        return

    f = open(args.out, "w", newline="")
    w = csv.writer(f)
    w.writerow(["state", "f_set_MHz", "f_actual_MHz", "rate_fps", "start_s", "end_s",
                "images", "images_per_s", "die_temp_C"])

    print("1) No overlay yet: note the meter now (board idle with PYNQ running).")
    window(w, "no_overlay", "", "", "", args.seconds, lambda end: time.sleep(
        max(0.0, end - time.time())) or 0)

    accel = load_accel(args, args.batch, args.clocks[0])
    thr = None if args.no_halt else Fclk0Throttle()

    def sleep_until(end):
        time.sleep(max(0.0, end - time.time()))
        return 0

    def halted_idle(end):
        thr.stop()
        sleep_until(end)
        thr.run()
        return 0

    def continuous(end):
        n = 0
        while time.time() < end:
            accel.execute_on_buffers()
            n += args.batch
        return n

    def fixed(rate, halt):
        def run(end):
            n, period, nxt = 0, 1.0 / rate, time.time()
            while nxt < end:
                if halt:
                    thr.run()
                accel.execute_on_buffers(batch_size=1)  # returns after the output DMA is done
                if halt:
                    thr.stop()
                n += 1
                nxt += period
                time.sleep(max(0.0, nxt - time.time()))
            if halt:
                thr.run()
            return n
        return run

    for fs in args.clocks:
        Clocks.fclk0_mhz = fs
        time.sleep(3)
        fa = round(Clocks.fclk0_mhz, 2)
        print(f"2) clock set {fs} MHz, actual {fa} MHz")
        for r in range(args.repeats):
            window(w, "idle_overlay", fs, fa, "", args.seconds, sleep_until)
            if thr:
                window(w, "idle_halted", fs, fa, "", args.seconds, halted_idle)
            tput = window(w, "continuous", fs, fa, "", args.seconds, continuous)
            for rate in args.rates:
                if rate < 0.9 * tput:
                    window(w, "fixed_rate", fs, fa, rate, args.seconds, fixed(rate, False))
                    if thr:
                        window(w, "fixed_rate_halt", fs, fa, rate, args.seconds,
                               fixed(rate, True))
            f.flush()
            print(f"   repeat {r + 1}/{args.repeats}: continuous {tput:.0f} images/s")
    f.close()
    print("done; cut the meter log with", args.out, "and take the median of the repeats")


if __name__ == "__main__":
    main()
